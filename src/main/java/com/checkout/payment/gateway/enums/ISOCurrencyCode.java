package com.checkout.payment.gateway.enums;

/**
 * Enumeration representing supported ISO 4217 currency codes.
 * <p>
 * This enum defines the set of currencies that the payment gateway
 * currently supports for processing transactions. Each constant
 * corresponds to a standard three-letter ISO currency code.
 * </p>
 */
public enum ISOCurrencyCode {
  /**
   * Euro (EUR) — the official currency of the Eurozone.
   */
  EUR,

  /**
   * British Pound Sterling (GBP) — the official currency of the United Kingdom.
   */
  GBP,

  /**
   * United States Dollar (USD) — the official currency of the United States.
   */
  USD
}
